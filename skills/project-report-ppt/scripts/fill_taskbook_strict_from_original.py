def auto_fit_body_inside_background(path: Path) -> None:
    root = ET.fromstring(path.read_bytes())
    changed = False
    shapes = root.findall(".//p:sp", NS)
    template_metrics = _template_body_background_metrics(_slide_part_name(path))

    shape_boxes = _collect_shape_boxes(root)

    visual_tops: list[int] = []
    for tag in ("pic", "grpSp", "graphicFrame"):
        for node in root.findall(f".//p:{tag}", NS):
            if tag == "grpSp":
                xfrm = node.find("./p:grpSpPr/a:xfrm", NS)
            elif tag == "graphicFrame":
                xfrm = node.find("./p:xfrm", NS)
            else:
                xfrm = node.find("./p:spPr/a:xfrm", NS)
            off = xfrm.find("./a:off", NS) if xfrm is not None else None
            if off is not None:
                visual_tops.append(int(off.get("y", "0")))

    for shape, x, y, cx, cy, text in shape_boxes:
        if _shape_name(shape) != "矩形 7" or len(text) < 40:
            continue

        bg_candidate = _find_body_background(shape, shape_boxes)
        if bg_candidate is None:
            continue

        bg_shape, bg_x, bg_y, bg_cx, bg_cy, _ = bg_candidate
        shape_xfrm = shape.find("./p:spPr/a:xfrm", NS)
        shape_off = shape_xfrm.find("./a:off", NS) if shape_xfrm is not None else None
        shape_ext = shape_xfrm.find("./a:ext", NS) if shape_xfrm is not None else None
        bg_xfrm = bg_shape.find("./p:spPr/a:xfrm", NS)
        bg_ext = bg_xfrm.find("./a:ext", NS) if bg_xfrm is not None else None
        if shape_off is None or shape_ext is None or bg_ext is None:
            continue

        template_bg_y = bg_y
        template_bg_cy = bg_cy
        template_body_y = y
        template_body_cy = int(shape_ext.get("cy", "0"))
        top_margin = BODY_BG_TOP_PAD
        bottom_margin = BODY_BG_BOTTOM_PAD

        if template_metrics is not None:
            template_bg_y = template_metrics["bg_y"]
            template_bg_cy = template_metrics["bg_cy"]
            template_body_y = template_metrics["body_y"]
            template_body_cy = template_metrics["body_cy"]
            top_margin = template_metrics["top_margin"]
            bottom_margin = template_metrics["bottom_margin"]

        current_bg_cy = int(bg_ext.get("cy", "0"))
        if bg_y != template_bg_y:
            bg_off = bg_xfrm.find("./a:off", NS) if bg_xfrm is not None else None
            if bg_off is not None:
                bg_off.set("y", str(template_bg_y))
                bg_y = template_bg_y
                changed = True
        if current_bg_cy < int(template_bg_cy * TEMPLATE_BG_CY_FLOOR_RATIO):
            bg_ext.set("cy", str(template_bg_cy))
            current_bg_cy = template_bg_cy
            changed = True

        current_body_cy = int(shape_ext.get("cy", "0"))
        if current_body_cy < int(template_body_cy * TEMPLATE_BODY_CY_FLOOR_RATIO):
            shape_ext.set("cy", str(template_body_cy))
            current_body_cy = template_body_cy
            changed = True

        body_target_top = max(template_body_y, bg_y + top_margin)
        if y != body_target_top:
            shape_off.set("y", str(body_target_top))
            y = body_target_top
            changed = True

        body_top = y
        body_bottom = body_top + current_body_cy
        bg_bottom = bg_y + current_bg_cy

        lower_tops = _lower_visual_tops(shape_boxes, visual_tops, shape, body_top)
        max_bg_bottom = min(lower_tops) - BODY_VISUAL_GAP if lower_tops else None
        if max_bg_bottom is not None and body_top + current_body_cy > max_bg_bottom and body_top > bg_y:
            new_body_top = max(bg_y, max_bg_bottom - current_body_cy)
            if new_body_top < body_top:
                shape_off.set("y", str(new_body_top))
                body_top = new_body_top
                body_bottom = body_top + current_body_cy
                changed = True
        desired_bg_bottom = body_bottom + bottom_margin + BODY_BG_EXTRA_SLACK
        if bg_bottom < desired_bg_bottom:
            new_bg_bottom = desired_bg_bottom
            if max_bg_bottom is not None:
                new_bg_bottom = min(new_bg_bottom, max_bg_bottom)
            new_bg_cy = max(new_bg_bottom - bg_y, int(template_bg_cy * TEMPLATE_BG_CY_FLOOR_RATIO))
            if int(bg_ext.get("cy", "0")) != new_bg_cy:
                bg_ext.set("cy", str(new_bg_cy))
                bg_bottom = bg_y + new_bg_cy
                changed = True

        if max_bg_bottom is not None and bg_bottom > max_bg_bottom:
            new_bg_cy = max(max_bg_bottom - bg_y, int(template_bg_cy * TEMPLATE_BG_CY_FLOOR_RATIO))
            if int(bg_ext.get("cy", "0")) != new_bg_cy:
                bg_ext.set("cy", str(new_bg_cy))
                bg_bottom = bg_y + new_bg_cy
                changed = True

        allowed_body_bottom = bg_bottom - bottom_margin
        if max_bg_bottom is not None:
            allowed_body_bottom = min(allowed_body_bottom, max_bg_bottom)
        if body_top + current_body_cy > allowed_body_bottom:
            new_body_cy = max(allowed_body_bottom - body_top, MIN_BODY_TEXTBOX_HEIGHT)
            new_body_cy = max(new_body_cy, int(template_body_cy * TEMPLATE_BODY_CY_FLOOR_RATIO))
            if new_body_cy != current_body_cy:
                shape_ext.set("cy", str(new_body_cy))
                changed = True

    if changed:
        path.write_bytes(ET.tostring(root, encoding="utf-8", xml_declaration=True))


def _set_red_emphasis(r_pr: ET.Element) -> None:
    r_pr.set("b", "1")
    for child in list(r_pr):
        if child.tag in {f"{{{NS['a']}}}solidFill", f"{{{NS['a']}}}noFill", f"{{{NS['a']}}}gradFill", f"{{{NS['a']}}}blipFill", f"{{{NS['a']}}}pattFill"}:
            r_pr.remove(child)
    solid_fill = ET.Element(f"{{{NS['a']}}}solidFill")
    srgb = ET.SubElement(solid_fill, f"{{{NS['a']}}}srgbClr")
    srgb.set("val", EMPHASIS_COLOR)
    r_pr.insert(0, solid_fill)


def _set_normal_weight(r_pr: ET.Element) -> None:
    r_pr.set("b", "0")


def _run_is_emphasized(r_pr: ET.Element | None) -> bool:
    if r_pr is None:
        return False
    srgb = r_pr.find("./a:solidFill/a:srgbClr", NS)
    return srgb is not None and srgb.get("val") == EMPHASIS_COLOR


def _normalize_paragraph_runs(paragraph: ET.Element) -> None:
    for run in paragraph.findall("./a:r", NS):
        r_pr = run.find("./a:rPr", NS)
        if not _run_is_emphasized(r_pr):
            if r_pr is None:
                r_pr = ET.Element(f"{{{NS['a']}}}rPr")
                run.insert(0, r_pr)
            _set_normal_weight(r_pr)
    end_para_r_pr = paragraph.find("./a:endParaRPr", NS)
    if end_para_r_pr is not None:
        _set_normal_weight(end_para_r_pr)


def _build_run(text: str, template_r_pr: ET.Element | None, emphasized: bool) -> ET.Element:
    run = ET.Element(f"{{{NS['a']}}}r")
    if template_r_pr is not None:
        r_pr = copy.deepcopy(template_r_pr)
    else:
        r_pr = ET.Element(f"{{{NS['a']}}}rPr")
    if emphasized:
        _set_red_emphasis(r_pr)
    else:
        _set_normal_weight(r_pr)
    run.append(r_pr)
    t = ET.SubElement(run, f"{{{NS['a']}}}t")
    if text.startswith(" ") or text.endswith(" "):
        t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    t.text = text
    return run


def _emphasize_paragraph(paragraph: ET.Element) -> None:
    text = "".join(node.text or "" for node in paragraph.findall(".//a:t", NS))
    if not text:
        return
    pattern = re.compile("|".join(re.escape(keyword) for keyword in EMPHASIS_KEYWORDS))
    matches = []
    for candidate in pattern.finditer(text):
        if any(not (candidate.end() <= kept.start() or candidate.start() >= kept.end()) for kept in matches):
            continue
        matches.append(candidate)
        if len(matches) >= BODY_EMPHASIS_MAX_MATCHES:
            break
    if not matches:
        _normalize_paragraph_runs(paragraph)
        return

    template_r_pr = paragraph.find(".//a:rPr", NS)
    if template_r_pr is None:
        template_r_pr = paragraph.find("./a:endParaRPr", NS)

    p_pr = paragraph.find("./a:pPr", NS)
    end_para_r_pr = paragraph.find("./a:endParaRPr", NS)
    for child in list(paragraph):
        if child is p_pr or child is end_para_r_pr:
            continue
        paragraph.remove(child)

    cursor = 0
    insert_at = 1 if p_pr is not None else 0
    for match in matches:
        start, end = match.span()
        if start > cursor:
            paragraph.insert(insert_at, _build_run(text[cursor:start], template_r_pr, emphasized=False))
            insert_at += 1
        paragraph.insert(insert_at, _build_run(text[start:end], template_r_pr, emphasized=True))
        insert_at += 1
        cursor = end
    if cursor < len(text):
        paragraph.insert(insert_at, _build_run(text[cursor:], template_r_pr, emphasized=False))
    _normalize_paragraph_runs(paragraph)


def emphasize_body_keywords(path: Path) -> None:
    root = ET.fromstring(path.read_bytes())

    for shape in root.findall(".//p:sp", NS):
        c_nv_pr = shape.find("./p:nvSpPr/p:cNvPr", NS)
        shape_name = c_nv_pr.get("name") if c_nv_pr is not None else ""
        if shape_name in BODY_EXCLUDED_SHAPE_NAMES:
            continue
        shape_text = "".join(node.text or "" for node in shape.findall(".//a:t", NS)).strip()
        if len(shape_text) < BODY_EMPHASIS_MIN_CHARS:
            continue
        if shape_text.startswith(BODY_EXCLUDED_TEXT_PREFIXES):
            continue
        for paragraph in shape.findall("./p:txBody/a:p", NS):
            _emphasize_paragraph(paragraph)

    path.write_bytes(ET.tostring(root, encoding="utf-8", xml_declaration=True))


def protected_shape_names_for_slide(slide_path: str) -> set[str]:
    names = set(BASE_PROTECTED_SHAPE_NAMES)
    if slide_path in DYNAMIC_SUBTITLE_SLIDES:
        names.discard("矩形 107")
