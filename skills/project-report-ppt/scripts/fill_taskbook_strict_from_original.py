def restore_template_scaffold(slide_path: str, original_bytes: bytes, patched_path: Path) -> None:
    if slide_path in FULL_TEMPLATE_SLIDES:
        patched_path.write_bytes(original_bytes)
        return
    restore_protected_shapes(slide_path, original_bytes, patched_path)


def restore_protected_shapes(slide_path: str, original_bytes: bytes, patched_path: Path) -> None:
    original_root = ET.fromstring(original_bytes)
    patched_root = ET.fromstring(patched_path.read_bytes())
    protected_names = protected_shape_names_for_slide(slide_path)

    original_shapes = original_root.findall(".//p:sp", NS)
    patched_shapes = patched_root.findall(".//p:sp", NS)

    for original_shape, patched_shape in zip(original_shapes, patched_shapes):
        c_nv_pr = original_shape.find("./p:nvSpPr/p:cNvPr", NS)
        if c_nv_pr is None or c_nv_pr.get("name") not in protected_names:
            continue

        original_text_nodes = original_shape.findall(".//a:t", NS)
        patched_text_nodes = patched_shape.findall(".//a:t", NS)
        for original_node, patched_node in zip(original_text_nodes, patched_text_nodes):
            patched_node.text = original_node.text

    patched_path.write_bytes(ET.tostring(patched_root, encoding="utf-8", xml_declaration=True))


def replace_global_template_text(path: Path, slide_path: str) -> None:
    if slide_path in FULL_TEMPLATE_SLIDES:
        return
    root = ET.fromstring(path.read_bytes())
    changed = False
    eligible_shapes: list[ET.Element] = []
    for shape in root.findall(".//p:sp", NS):
        c_nv_pr = shape.find("./p:nvSpPr/p:cNvPr", NS)
        shape_name = c_nv_pr.get("name", "") if c_nv_pr is not None else ""
        if shape_name == "标题 4":
            continue
        if shape_name == "矩形 107" and slide_path not in DYNAMIC_SUBTITLE_SLIDES:
            continue
        eligible_shapes.append(shape)
        text_nodes = shape.findall(".//a:t", NS)
        if not text_nodes:
            continue
        full_text = "".join(node.text or "" for node in text_nodes).strip()
        replacement = GLOBAL_TEXT_REPLACEMENTS.get(full_text)
        if replacement is not None and replacement != full_text:
            text_nodes[0].text = replacement
            for node in text_nodes[1:]:
                node.text = ""
            changed = True
    for shape in eligible_shapes:
        for node in shape.findall(".//a:t", NS):
            text = node.text or ""
            replacement = GLOBAL_TEXT_REPLACEMENTS.get(text)
            if replacement is not None and replacement != text:
                node.text = replacement
                changed = True
    if changed:
        path.write_bytes(ET.tostring(root, encoding="utf-8", xml_declaration=True))


