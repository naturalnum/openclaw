def rewrite_slide_relationships(rels_path: Path, placeholder_target: str) -> bool:
    slide_match = re.search(r"slide(\d+)\.xml\.rels$", rels_path.name)
    if slide_match and int(slide_match.group(1)) in PRESERVE_TEMPLATE_IMAGE_SLIDES:
        return False
    root = ET.fromstring(rels_path.read_bytes())
    changed = False
    for rel in root.findall(f"{{{REL_NS}}}Relationship"):
        rel_type = rel.attrib.get("Type", "")
        target = rel.attrib.get("Target", "")
        if rel_type.endswith("/image") and target.startswith("../media/"):
            rel.set("Target", placeholder_target)
            changed = True
    if changed:
        rels_path.write_bytes(ET.tostring(root, encoding="utf-8", xml_declaration=True))
    return changed


def collect_referenced_media_paths(root_dir: Path) -> set[str]:
    referenced: set[str] = set()
    for rels_path in root_dir.rglob("*.rels"):
        rel_root = ET.fromstring(rels_path.read_bytes())
        rels_rel = rels_path.relative_to(root_dir).as_posix()
        if "/_rels/" in rels_rel:
            source_rel = rels_rel.replace("/_rels/", "/").removesuffix(".rels")
            source_base = posixpath.dirname(source_rel)
        else:
            source_base = posixpath.dirname(rels_rel)
        for rel in rel_root.findall(f"{{{REL_NS}}}Relationship"):
            target = rel.attrib.get("Target", "")
            if not target or target.startswith(("http://", "https://", "file://")):
                continue
            normalized = posixpath.normpath(posixpath.join(source_base, target))
            if normalized.startswith("ppt/media/"):
                referenced.add(normalized)
    return referenced


def collect_slide_image_media_paths(root_dir: Path) -> set[str]:
    referenced: set[str] = set()
    rels_root = root_dir / "ppt" / "slides" / "_rels"
    if not rels_root.exists():
        return referenced
    for rels_path in rels_root.glob("slide*.xml.rels"):
        rel_root = ET.fromstring(rels_path.read_bytes())
        for rel in rel_root.findall(f"{{{REL_NS}}}Relationship"):
            rel_type = rel.attrib.get("Type", "")
            target = rel.attrib.get("Target", "")
            if not rel_type.endswith("/image") or not target.startswith("../media/"):
                continue
            normalized = posixpath.normpath(posixpath.join("ppt/slides", target))
            if normalized.startswith("ppt/media/"):
                referenced.add(normalized)
    return referenced


def prune_unused_media(root_dir: Path, referenced_media: set[str]) -> int:
    media_dir = root_dir / "ppt" / "media"
    if not media_dir.exists():
        return 0

    removed = 0
    for media_path in media_dir.iterdir():
        rel_path = f"ppt/media/{media_path.name}"
        if rel_path in referenced_media:
            continue
        media_path.unlink()
        removed += 1
    return removed


def _watermark_image_bytes(image_bytes: bytes, suffix: str, watermark_text: str) -> bytes | None:
    try:
        with Image.open(BytesIO(image_bytes)) as img:
            base = img.convert("RGBA")
    except Exception:
        return None

    width, height = base.size
    overlay = Image.new("RGBA", base.size, (255, 255, 255, 0))
    draw = ImageDraw.Draw(overlay)

    font_size = max(42, min(width, height) // 7)
    try:
        font = ImageFont.truetype("/System/Library/Fonts/Supplemental/Arial Unicode.ttf", font_size)
    except OSError:
        font = ImageFont.load_default()

    bbox = draw.textbbox((0, 0), watermark_text, font=font)
    text_w = bbox[2] - bbox[0]
    text_h = bbox[3] - bbox[1]
    step_x = max(text_w + 90, width // 2)
    step_y = max(text_h + 80, height // 2)

    for x in range(-step_x // 2, width + step_x, step_x):
        for y in range(-step_y // 2, height + step_y, step_y):
            draw.text(
                (x + 4, y + 4),
                watermark_text,
                fill=(255, 255, 255, 70),
                font=font,
                stroke_width=2,
                stroke_fill=(255, 255, 255, 70),
            )
            draw.text(
                (x, y),
                watermark_text,
                fill=(192, 0, 0, 108),
                font=font,
                stroke_width=2,
                stroke_fill=(160, 0, 0, 108),
            )

    overlay = overlay.rotate(24, resample=Image.Resampling.BICUBIC, expand=False)
    result = Image.alpha_composite(base, overlay)
    buffer = BytesIO()
    suffix = suffix.lower()
    if suffix in {".jpg", ".jpeg"}:
        result.convert("RGB").save(buffer, format="JPEG", quality=92)
    elif suffix == ".png":
        result.save(buffer, format="PNG")
    elif suffix == ".bmp":
        result.convert("RGB").save(buffer, format="BMP")
    elif suffix in {".tif", ".tiff"}:
        result.save(buffer, format="TIFF")
    else:
        return None
    return buffer.getvalue()


def watermark_slide_images(root_dir: Path, watermark_text: str = "参考素材") -> None:
    media_paths = collect_slide_image_media_paths(root_dir)
    for rel_path in sorted(media_paths):
        media_file = root_dir / rel_path
        if not media_file.exists():
            continue
        watermarked = _watermark_image_bytes(media_file.read_bytes(), media_file.suffix, watermark_text)
        if watermarked is None:
            continue
        media_file.write_bytes(watermarked)


def replace_slide_images_with_placeholder(root_dir: Path) -> None:
    placeholder_rel_target = "../media/placeholder-static-image.png"
    rels_root = root_dir / "ppt" / "slides" / "_rels"
    if rels_root.exists():
        for rels_path in rels_root.glob("slide*.xml.rels"):
            rewrite_slide_relationships(rels_path, placeholder_rel_target)

    media_dir = root_dir / "ppt" / "media"
    media_dir.mkdir(parents=True, exist_ok=True)
    (media_dir / "placeholder-static-image.png").write_bytes(build_placeholder_png())

    referenced_media = collect_referenced_media_paths(root_dir)
    prune_unused_media(root_dir, referenced_media)


def main() -> None:
    args = parse_args()
    input_path = Path(args.input).expanduser().resolve()
    output_path = Path(args.output).expanduser().resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    manifest = load_manifest(Path(args.manifest)) if args.manifest else None
    node_updates = copy.deepcopy(SLIDE_NODE_UPDATES)
    table_text_updates = copy.deepcopy(SLIDE_TABLE_TEXT_UPDATES)
    shape_text_updates = copy.deepcopy(SLIDE_SHAPE_TEXT_UPDATES)
    manifest_node_updates, manifest_shape_updates, manifest_table_updates = build_updates_from_manifest(manifest)
    for slide_path, updates in manifest_node_updates.items():
        node_updates.setdefault(slide_path, {}).update(updates)
    for slide_path, updates in manifest_shape_updates.items():
        if slide_path in MANIFEST_OVERRIDE_SHAPE_SLIDES:
            shape_text_updates[slide_path] = copy.deepcopy(updates)
        else:
            shape_text_updates.setdefault(slide_path, {}).update(updates)
    for slide_path, updates in manifest_table_updates.items():
        table_text_updates.setdefault(slide_path, {}).update(updates)

    with TemporaryDirectory() as tmpdir:
        tmpdir_path = Path(tmpdir)
        with ZipFile(input_path) as zin:
            zin.extractall(tmpdir_path)

        ORIGINAL_SLIDE_XMLS.clear()
        for original_slide in sorted((tmpdir_path / "ppt" / "slides").glob("slide*.xml")):
            ORIGINAL_SLIDE_XMLS[_slide_part_name(original_slide)] = original_slide.read_bytes()

        for slide_path, updates in node_updates.items():
            patched_slide_path = tmpdir_path / slide_path
            original_slide_bytes = patched_slide_path.read_bytes()
            patch_xml(patched_slide_path, updates)
            restore_template_scaffold(slide_path, original_slide_bytes, patched_slide_path)

        for slide_path, table_updates in table_text_updates.items():
            patch_table_texts(tmpdir_path / slide_path, table_updates)

        for slide_path, shape_updates in shape_text_updates.items():
            patch_shape_texts(tmpdir_path / slide_path, shape_updates)

        for slide_path, shape_updates in SLIDE_SHAPE_PARAGRAPH_UPDATES.items():
            patch_shape_paragraph_texts(tmpdir_path / slide_path, shape_updates)

        for slide_path, height_deltas in SLIDE_SHAPE_HEIGHT_DELTAS.items():
            adjust_shape_heights(tmpdir_path / slide_path, height_deltas)

        for slide_path, font_sizes in SLIDE_SHAPE_FONT_SIZES.items():
            patch_shape_font_sizes(tmpdir_path / slide_path, font_sizes)

        for slide_path, font_sizes in SLIDE_TABLE_FONT_SIZES.items():
            patch_table_font_sizes(tmpdir_path / slide_path, font_sizes)

        for slide_path, font_colors in SLIDE_TABLE_FONT_COLORS.items():
            patch_table_font_colors(tmpdir_path / slide_path, font_colors)

        for slide_path, cell_positions in TASK_TITLE_TABLE_CELLS.items():
            patch_task_title_table_cells(tmpdir_path / slide_path, cell_positions)

        for slide_path, widths in SLIDE_SHAPE_WIDTHS.items():
            patch_shape_widths(tmpdir_path / slide_path, widths)

        for slide_path, shape_indices in SLIDE_SHAPE_WRAP_NONE.items():
            patch_shape_wrap_none(tmpdir_path / slide_path, shape_indices)

        for slide_file in sorted((tmpdir_path / "ppt" / "slides").glob("slide*.xml")):
            compress_long_heading_texts(slide_file)
            compress_long_body_texts(slide_file)
            auto_fit_long_heading_shapes(slide_file)
            auto_fit_diagram_text_shapes(slide_file)
            auto_separate_subtitle_and_heading(slide_file)
            auto_separate_heading_and_body(slide_file)
            auto_avoid_body_visual_overlap(slide_file)
            auto_fit_body_inside_background(slide_file)
            emphasize_body_keywords(slide_file)
            replace_global_template_text(slide_file, slide_file.relative_to(tmpdir_path).as_posix())
            compress_long_body_texts(slide_file)
            auto_fit_diagram_text_shapes(slide_file)
            auto_fit_body_inside_background(slide_file)
            patch_figure_guidance_font_sizes(slide_file)
            patch_visual_guidance_font_sizes(slide_file)
            locked_font_sizes = TEMPLATE_LOCKED_SHAPE_FONT_SIZES.get(
                slide_file.relative_to(tmpdir_path).as_posix()
            )
            if locked_font_sizes:
                patch_shape_font_sizes(slide_file, locked_font_sizes)
            locked_texts = TEMPLATE_LOCKED_SHAPE_TEXTS.get(
                slide_file.relative_to(tmpdir_path).as_posix()
            )
            if locked_texts:
                patch_shape_texts(slide_file, locked_texts)
            slide_part = slide_file.relative_to(tmpdir_path).as_posix()
            if slide_part in TEMPLATE_BASELINE_FONT_SLIDES:
                original_bytes = ORIGINAL_SLIDE_XMLS.get(slide_part)
