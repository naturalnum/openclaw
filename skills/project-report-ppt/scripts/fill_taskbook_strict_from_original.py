def _template_body_background_metrics(slide_part: str) -> dict[str, int] | None:
    slide_xml = ORIGINAL_SLIDE_XMLS.get(slide_part)
    if not slide_xml:
        return None
    root = ET.fromstring(slide_xml)
    shape_boxes = _collect_shape_boxes(root)
    for shape, x, y, cx, cy, text in shape_boxes:
        if _shape_name(shape) != "矩形 7" or not text:
            continue
        bg_candidate = _find_body_background(shape, shape_boxes)
        if bg_candidate is None:
            continue
        _, bg_x, bg_y, bg_cx, bg_cy, _ = bg_candidate
        return {
            "body_x": x,
            "body_y": y,
            "body_cx": cx,
            "body_cy": cy,
            "bg_x": bg_x,
            "bg_y": bg_y,
            "bg_cx": bg_cx,
            "bg_cy": bg_cy,
            "top_margin": max(y - bg_y, 0),
            "bottom_margin": max((bg_y + bg_cy) - (y + cy), 0),
        }
    return None


def _lower_visual_tops(
    shape_boxes: list[tuple[ET.Element, int, int, int, int, str]],
    visual_tops: list[int],
    current_shape: ET.Element,
    current_y: int,
) -> list[int]:
    lower_tops = [top for top in visual_tops if top > current_y + 100000]
    for other_shape, _, oy, _, _, other_text in shape_boxes:
        if other_shape is current_shape:
            continue
        if oy <= current_y + 100000:
            continue
        if other_text and len(other_text) >= 25:
            continue
        lower_tops.append(oy)
    return lower_tops


def _find_body_background(
    body_shape: ET.Element,
    shape_boxes: list[tuple[ET.Element, int, int, int, int, str]],
) -> tuple[ET.Element, int, int, int, int, str] | None:
    body_box = _shape_box(body_shape)
    if body_box is None:
        return None
    bx, by, bcx, bcy = body_box
    body_mid_x = bx + bcx / 2
    best: tuple[float, tuple[ET.Element, int, int, int, int, str]] | None = None
    for candidate in shape_boxes:
        shape, x, y, cx, cy, text = candidate
        if shape is body_shape or text:
            continue
        if cx < 7000000 or cy < 700000:
            continue
        horizontal_overlap = min(bx + bcx, x + cx) - max(bx, x)
        if horizontal_overlap <= bcx * 0.65:
            continue
        if abs((x + cx / 2) - body_mid_x) > 500000:
            continue
        if y > by + 250000:
            continue
        if y + cy < by + 500000:
            continue
        score = abs(y - by) + abs(cx - bcx) + abs(x - bx)
        if best is None or score < best[0]:
            best = (score, candidate)
    return best[1] if best else None


