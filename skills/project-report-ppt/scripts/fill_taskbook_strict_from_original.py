def patch_shape_font_sizes_from_original(slide_path: Path, original_bytes: bytes) -> None:
    root = ET.fromstring(slide_path.read_bytes())
    original_root = ET.fromstring(original_bytes)
    shapes = root.findall(".//p:sp", NS)
    original_shapes = original_root.findall(".//p:sp", NS)
    changed = False
    for idx, shape in enumerate(shapes):
        if idx >= len(original_shapes):
            continue
        if not _shape_text(shape):
            continue
        original_first = original_shapes[idx].find(".//a:r/a:rPr", NS)
        if original_first is None:
            continue
        size = original_first.get("sz")
        if not size:
            continue
        for node in shape.findall(".//a:rPr", NS):
            if node.get("sz") != size:
                node.set("sz", size)
                changed = True
        for node in shape.findall(".//a:endParaRPr", NS):
            if node.get("sz") != size:
                node.set("sz", size)
                changed = True
    if changed:
        slide_path.write_bytes(ET.tostring(root, encoding="utf-8", xml_declaration=True))


