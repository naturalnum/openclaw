def patch_xml(path: Path, updates: dict[int, str]) -> None:
    root = ET.fromstring(path.read_bytes())
    nodes = root.findall(".//a:t", NS)
    for index, value in updates.items():
        if index < len(nodes):
            nodes[index].text = value
    path.write_bytes(ET.tostring(root, encoding="utf-8", xml_declaration=True))


def patch_shape_texts(path: Path, shape_updates: dict[int, str]) -> None:
    root = ET.fromstring(path.read_bytes())
    shapes = root.findall(".//p:sp", NS)
    for shape_index, value in shape_updates.items():
        if shape_index >= len(shapes):
            continue
        text_nodes = shapes[shape_index].findall(".//a:t", NS)
        if not text_nodes:
            continue
        text_nodes[0].text = value
        for node in text_nodes[1:]:
            node.text = ""
    path.write_bytes(ET.tostring(root, encoding="utf-8", xml_declaration=True))


def patch_shape_paragraph_texts(path: Path, shape_updates: dict[int, list[str]]) -> None:
    root = ET.fromstring(path.read_bytes())
    shapes = root.findall(".//p:sp", NS)
    for shape_index, paragraphs in shape_updates.items():
        if shape_index >= len(shapes):
            continue
        shape = shapes[shape_index]
        para_nodes = shape.findall("./p:txBody/a:p", NS)
        if not para_nodes:
            continue
        if len(paragraphs) > len(para_nodes):
            tx_body = shape.find("./p:txBody", NS)
            template_para = para_nodes[-1]
            for _ in range(len(paragraphs) - len(para_nodes)):
                tx_body.append(copy.deepcopy(template_para))
            para_nodes = shape.findall("./p:txBody/a:p", NS)
        for para_index, para in enumerate(para_nodes):
            text_nodes = para.findall(".//a:t", NS)
            value = paragraphs[para_index] if para_index < len(paragraphs) else ""
            if text_nodes:
                text_nodes[0].text = value
                for node in text_nodes[1:]:
                    node.text = ""
    path.write_bytes(ET.tostring(root, encoding="utf-8", xml_declaration=True))


