def patch_task_title_table_cells(path: Path, cell_positions: list[tuple[int, int, int]]) -> None:
    root = ET.fromstring(path.read_bytes())
    tables = root.findall(".//a:tbl", NS)
    changed = False
    for table_index, row_index, cell_index in cell_positions:
        if table_index >= len(tables):
            continue
        rows = tables[table_index].findall("a:tr", NS)
        if row_index >= len(rows):
            continue
        cells = rows[row_index].findall("a:tc", NS)
        if cell_index >= len(cells):
            continue
        cell = cells[cell_index]
        text = "".join(node.text for node in cell.findall(".//a:t", NS) if node.text).strip()
        match = re.match(r"^课题\s*([1-4])\s*：(.*)$", text)
        if not match:
            continue
        task_no, title = match.group(1), match.group(2).strip()
        paragraph = cell.find(".//a:p", NS)
        if paragraph is None:
            continue
        first_run = paragraph.find("a:r", NS)
        if first_run is None:
            continue
        first_rpr = first_run.find("a:rPr", NS)
        if first_rpr is None:
            continue

        def make_run(text_value: str, color: str | None, bold: str) -> ET.Element:
            run = ET.Element(f"{{{NS['a']}}}r")
            rpr = copy.deepcopy(first_rpr)
            rpr.set("sz", "1600")
            rpr.set("b", bold)
            solid_fill = rpr.find("a:solidFill", NS)
            if color is None:
                if solid_fill is not None:
                    rpr.remove(solid_fill)
            else:
                if solid_fill is None:
                    solid_fill = ET.SubElement(rpr, f"{{{NS['a']}}}solidFill")
                srgb = solid_fill.find("a:srgbClr", NS)
                if srgb is None:
                    srgb = ET.SubElement(solid_fill, f"{{{NS['a']}}}srgbClr")
                srgb.set("val", color)
            run.append(rpr)
            t = ET.SubElement(run, f"{{{NS['a']}}}t")
            t.text = text_value
            return run

        end_para = paragraph.find("a:endParaRPr", NS)
        end_para_copy = copy.deepcopy(end_para) if end_para is not None else None
        paragraph[:] = [
            make_run("课题", "C00000", "1"),
            make_run(task_no, "C00000", "1"),
            make_run("：", "000000", "0"),
            make_run(title, "014245", "0"),
        ]
        if end_para_copy is not None:
            end_para_copy.set("sz", "1600")
            paragraph.append(end_para_copy)
        changed = True
    if changed:
        path.write_bytes(ET.tostring(root, encoding="utf-8", xml_declaration=True))


def adjust_shape_heights(path: Path, height_deltas: dict[int, int]) -> None:
    root = ET.fromstring(path.read_bytes())
    shapes = root.findall(".//p:sp", NS)
    for shape_index, delta in height_deltas.items():
        if shape_index >= len(shapes):
            continue
        xfrm = shapes[shape_index].find("./p:spPr/a:xfrm", NS)
        if xfrm is None:
            continue
        ext = xfrm.find("./a:ext", NS)
        if ext is None or "cy" not in ext.attrib:
            continue
        ext.set("cy", str(int(ext.get("cy")) + delta))
    path.write_bytes(ET.tostring(root, encoding="utf-8", xml_declaration=True))


