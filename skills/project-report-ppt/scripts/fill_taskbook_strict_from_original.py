def _set_all_shape_font_sizes(shape: ET.Element, size: int) -> None:
    for node in shape.findall(".//a:rPr", NS):
        node.set("sz", str(size))
    for node in shape.findall(".//a:defRPr", NS):
        node.set("sz", str(size))
    for node in shape.findall(".//a:endParaRPr", NS):
        node.set("sz", str(size))


def _shape_name(shape: ET.Element) -> str:
    c_nv_pr = shape.find("./p:nvSpPr/p:cNvPr", NS)
    return c_nv_pr.get("name") if c_nv_pr is not None else ""


def _shape_text(shape: ET.Element) -> str:
    return "".join(node.text or "" for node in shape.findall(".//a:t", NS)).strip()


def _shape_box(shape: ET.Element) -> tuple[int, int, int, int] | None:
    xfrm = shape.find("./p:spPr/a:xfrm", NS)
    off = xfrm.find("./a:off", NS) if xfrm is not None else None
    ext = xfrm.find("./a:ext", NS) if xfrm is not None else None
    if off is None or ext is None:
        return None
    return (
        int(off.get("x", "0")),
        int(off.get("y", "0")),
        int(ext.get("cx", "0")),
        int(ext.get("cy", "0")),
    )


def _shape_bodypr(shape: ET.Element) -> ET.Element | None:
    return shape.find("./p:txBody/a:bodyPr", NS)


def _shape_max_font_size(shape: ET.Element, default: int = 1400) -> int:
    sizes: list[int] = []
    for node in shape.findall(".//a:rPr", NS) + shape.findall(".//a:defRPr", NS) + shape.findall(".//a:endParaRPr", NS):
        sz = node.get("sz")
        if sz and sz.isdigit():
            sizes.append(int(sz))
    return max(sizes) if sizes else default


